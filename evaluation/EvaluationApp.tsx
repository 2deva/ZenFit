import React, { useEffect, useRef, useState } from 'react';
import { generateSessionFromBuilder, type WorkoutListConfig } from '../services/sessionGeneratorService';
import { useActivityState } from '../hooks/useActivityState';
import { SyncQueue } from '../services/sync/SyncQueue';
import { getSyncQueue } from '../services/storageService';
import { processVoiceCommand } from '../services/voiceCommandsService';

const session = generateSessionFromBuilder({ focus: 'mobility', duration: '5', level: 'beginner', equipment: 'bodyweight' });
const workout = session.props as WorkoutListConfig;
export function EvaluationApp() {
  const activity = useActivityState();
  const [user, setUser] = useState<'alice' | 'bob'>('alice');
  const [completed, setCompleted] = useState<number[]>([]);
  const [stored, setStored] = useState<number[]>([]);
  const [online, setOnline] = useState(true);
  const [queued, setQueued] = useState(getSyncQueue().length);
  const [status, setStatus] = useState('Connecting to the isolated database…');
  const [command, setCommand] = useState('go back');
  const onlineRef = useRef(true);
  const queueRef = useRef<SyncQueue | null>(null);
  const currentUserRef = useRef(user); currentUserRef.current = user;
  const loadProgress = async (selectedUser: string) => {
    const response = await fetch(`/api/evaluation/progress?user=${selectedUser}&workoutId=return-workout`);
    if (!response.ok) throw new Error('Local evaluation API is unavailable');
    const data = await response.json(); const indices = data.progress?.completed_indices || [];
    if (selectedUser === currentUserRef.current) setStored(indices);
    return indices as number[];
  };
  useEffect(() => {
    const queue = new SyncQueue({ isOnline: () => onlineRef.current, execute: async op => {
      if (op.type !== 'SAVE_WORKOUT_PROGRESS') return false;
      const response = await fetch('/api/evaluation/progress', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ user: op.payload.userId, workoutId: op.payload.workoutId, completedIndices: op.payload.completedIndices, activeIdx: op.payload.activeIdx }) });
      return response.ok;
    } });
    queueRef.current = queue;
    void queue.processQueue().then(() => loadProgress(currentUserRef.current)).then(indices => { setCompleted(indices); setQueued(getSyncQueue().length); setStatus('Ready · synthetic identities · isolated PostgreSQL'); }).catch(error => setStatus(error.message));
    return () => { queue.dispose(); queueRef.current = null; };
  }, []);
  const chooseUser = async (selectedUser: 'alice' | 'bob') => {
    setUser(selectedUser); currentUserRef.current = selectedUser;
    try { setCompleted(await loadProgress(selectedUser)); setStatus('Identity changed; database row policies remain active.'); }
    catch (error) { setStatus(String(error)); }
  };
  const completeExercise = async (index: number) => {
    const indices = [...new Set([...completed, index])]; setCompleted(indices);
    queueRef.current!.scheduleOperation('SAVE_WORKOUT_PROGRESS', { userId: user, workoutId: 'return-workout', completedIndices: indices, activeIdx: Math.min(index + 1, workout.exercises.length - 1) });
    await queueRef.current!.processQueue();
    setQueued(getSyncQueue().length);
    if (onlineRef.current) { await queueRef.current!.processQueue(); await loadProgress(user); setQueued(getSyncQueue().length); }
  };
  const toggleNetwork = async () => {
    onlineRef.current = !onlineRef.current; setOnline(onlineRef.current);
    if (onlineRef.current) {
      await queueRef.current!.processQueue(); await loadProgress(user); setQueued(getSyncQueue().length);
      setStatus('Pending changes replayed to isolated PostgreSQL.');
    } else setStatus('Simulated offline mode; changes stay in the real local sync queue.');
  };
  const timer = activity.activityTimers['evaluation-timer'];
  const voice = processVoiceCommand(command);
  return <main>
    <header><p className="eyebrow">ZENFIT · LOCAL EVALUATION</p><h1>A small restart.<br />A verifiable result.</h1><p>Exercise real session generation, timer controls, offline replay and database row isolation without API keys.</p></header>
    <aside role="status">{status}</aside>
    <section className="controls"><label>Fixture identity <select aria-label="Fixture identity" value={user} onChange={event => void chooseUser(event.target.value as 'alice' | 'bob')}><option value="alice">Alice</option><option value="bob">Bob</option></select></label><button onClick={() => void toggleNetwork()}>{online ? 'Go offline' : 'Go online and sync'}</button><span>Queued writes: <strong data-testid="queued">{queued}</strong></span></section>
    <div className="grid"><section className="card"><h2>1. Return workout</h2><p>{workout.title} · generated by the production session generator.</p><ol>{workout.exercises.map((exercise, index) => <li key={index}><span>{exercise.name}<small>{exercise.duration || exercise.reps}</small></span><button disabled={completed.includes(index)} onClick={() => void completeExercise(index)}>{completed.includes(index) ? 'Done' : `Complete ${index + 1}`}</button></li>)}</ol><p>Stored for {user}: <strong data-testid="stored">{stored.length}</strong> exercises</p><p className="note">Switch identities to check that one user's progress is not shown to another.</p></section>
    <section className="card"><h2>2. Shared activity clock</h2><output data-testid="timer">{timer?.remainingSeconds ?? 5}s</output><p data-testid="timer-state">{timer?.state || 'idle'}</p><div className="buttons"><button onClick={() => activity.startActivity({ activityId: 'evaluation-timer', type: 'timer', label: 'Evaluation reset', totalSeconds: 5 })}>Start 5-second reset</button><button disabled={timer?.state !== 'running'} onClick={() => activity.pauseActivity('evaluation-timer')}>Pause</button><button disabled={timer?.state !== 'paused'} onClick={() => activity.resumeActivity('evaluation-timer')}>Resume</button></div><h2>3. Voice intent</h2><label>Command<input aria-label="Voice command" value={command} onChange={event => setCommand(event.target.value)} /></label><p>Action: <strong data-testid="voice-action">{voice.action || 'No command'}</strong></p><p>Confirmation: {voice.requiresConfirmation ? 'required' : 'not required'}</p></section></div>
    <footer>This is a deterministic evaluation harness with synthetic users and fixtures; it does not test live Gemini, Google Calendar, Firebase token verification or a production Supabase deployment.</footer>
  </main>;
}
